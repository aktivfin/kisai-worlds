import assert from 'node:assert/strict';
import {placeWorldItem,assertPickup,distance} from '../server/world-items.mjs';
import {initialObjectives,updateObjectives,objectivesComplete} from '../server/objectives.mjs';
import {perceive,filterVoiceEvents} from '../server/perception.mjs';
import {reactToPlayerAction} from '../server/encounter.mjs';
import {setTurnTimer,TIMER_POLICY} from '../server/turns.mjs';
import {materializeCharacterCore,createNpcCombatant} from '../core/character.mjs';

const scene={id:'scene',title:'Сцена',narration:'Секрет у дальнего объекта',loot:[],combatants:[],geometry:{visibilityRadius:5,anchors:[{id:'entry',x:0,y:0,z:0},{id:'middle',x:4,y:0,z:0},{id:'exit',x:10,y:0,z:0}]}};
const character=materializeCharacterCore({concept:'Защитник',abilities:['Удар']});
const player={id:'a',position:{x:0,y:0,z:0,anchorId:'entry'},character,alive:true,capacity:6,profile:{id:'a'}};
const other={id:'b',position:{x:10,y:0,z:0,anchorId:'exit'},character:materializeCharacterCore({abilities:['Удар']}),alive:true,capacity:6,profile:{id:'b'}};
const room={scene,players:new Map([['a',player],['b',other]]),log:[{event:'SECRET',npcId:'hidden',action:'whisper',narration:'Секрет'}],turnOrder:['a','b'],turnCursor:0};
const item={id:'unique_1',serial:'KW-UNCHANGED',kind:'equipment',status:'run',ownerId:'a',provenance:[{type:'origin'}]};
placeWorldItem(item,scene,other.position,{droppedBy:'b'});
assert.equal(item.world.position.x,10);assert.equal(item.world.droppedBy,'b');
assert.throws(()=>assertPickup(item,scene,player,0,1),/loot_not_visible|loot_out_of_range/);
assert.doesNotThrow(()=>assertPickup(item,scene,other,0,1));
assert.throws(()=>assertPickup(item,scene,other,6,1),/run_inventory_full/);
assert.equal(distance(player.position,item.world.position),10);
const hiddenNpc={id:'hidden',hidden:true,status:'alive',position:{x:0,y:0,z:0}};
scene.combatants.push(hiddenNpc);
const pa=perceive(room,'a');assert.equal(pa.visibleLoot.length,0);assert.equal(pa.visibleNpc.length,0);
assert.equal(pa.knownLog.length,0);assert.equal(pa.visibleAnchors.some(x=>x.id==='exit'),false);
assert.deepEqual(filterVoiceEvents(room,'a',[{speakerType:'NPC',speakerId:'hidden',text:'secret'},{speakerType:'GM',text:'private'},{speakerType:'TIMER',text:'tick'}],'b').map(x=>x.speakerType),['TIMER']);
room.objectives=initialObjectives(scene);room.progress=100;
assert.equal(objectivesComplete(room),false,'UI progress cannot finish objective graph');
updateObjectives(room);assert.equal(objectivesComplete(room),true,'physical reach completes required objective');
assert.equal(room.objectives[0].state,'COMPLETED');

scene.combatants=[];
const npc=createNpcCombatant({id:'guard',name:'Страж',tier:1});
npc.position={x:10,y:0,z:0,anchorId:'exit'};npc.conditions={stun:1};scene.combatants.push(npc);
other.alive=false;
const deps={nextD20:()=>20,defenderFor:p=>p.character,dropInventory:()=>[]};
let step=reactToPlayerAction(room,deps);assert.equal(step.events[0].type,'NPC_STUNNED');assert.equal(npc.position.anchorId,'exit');
step=reactToPlayerAction(room,deps);assert.equal(step.events[0].type,'NPC_MOVED');assert.equal(npc.position.anchorId,'middle');
npc.conditions.slow=1;step=reactToPlayerAction(room,deps);assert.equal(step.events[0].type,'NPC_MOVED');
step=reactToPlayerAction(room,deps);assert.equal(step.events[0].type,'NPC_ATTACKED');
assert.equal(step.counterattack.attack.accuracy,npc.attributes.agility-2,'slow lowers NPC hit accuracy');
assert.equal(npc.conditions.slow,0);
room.nextTimerType='TRAP';setTurnTimer(room,1000);assert.equal(room.timer.deadlineAt,1000+TIMER_POLICY.TRAP);
room.nextTimerType='EXPLORATION';setTurnTimer(room,2000);assert.equal(room.timer,null);
console.log('World integrity PASS: physical loot, objective graph, NPC stun/move/attack/slow, private perception/voice, timer policy');
